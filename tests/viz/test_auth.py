from datetime import datetime, timezone

import pytest
from fastapi.testclient import TestClient

from schema.records import Identifier, Modality, Signal, UnifiedRecord
from storage.db import init_db, make_session_factory
from storage.repository import save_record
from tests.viz.test_app import _make_memory_engine
from viz.app import create_app
from viz.auth import (
    API_TOKEN_ENV,
    MIN_DISTINCT_CHARS,
    MIN_TOKEN_LENGTH,
    ApiTokenError,
    load_api_token,
)

PUBLIC_PATHS = ("/", "/static/map.js", "/static/leaflet.js", "/static/leaflet.css")
TOKEN = "0123456789abcdef" * 2


def _session_factory(rows: int = 0):
    engine = _make_memory_engine()
    init_db(engine)
    factory = make_session_factory(engine)
    with factory() as session:
        for i in range(rows):
            save_record(
                session,
                UnifiedRecord(
                    timestamp=datetime.now(timezone.utc),
                    lat=1.0,
                    lon=2.0,
                    survey_id="s",
                    operator_id="o",
                    modality=Modality.WIFI,
                    identifier=Identifier(bssid=f"AA:BB:CC:DD:EE:{i:02X}"),
                    signal=Signal(rssi=-40.0),
                ),
            )
    return factory


def _client(rows: int = 0) -> TestClient:
    return TestClient(create_app(_session_factory(rows), api_token=TOKEN))


def _every_route(client: TestClient) -> list[str]:
    paths = {route.path for route in client.app.routes if hasattr(route, "methods")}
    assert {"/", "/api/records"} <= paths
    return sorted(paths)


def test_every_route_but_the_static_shell_rejects_requests_without_a_token():
    client = _client()
    for path in _every_route(client):
        if path in PUBLIC_PATHS:
            continue
        response = client.get(path)
        assert response.status_code == 401, path
        assert response.headers["www-authenticate"] == "Bearer"


def test_autogenerated_docs_routes_are_not_exposed():
    client = _client()
    for path in ("/docs", "/redoc", "/openapi.json"):
        assert client.get(path, headers={"Authorization": f"Bearer {TOKEN}"}).status_code == 404
        assert client.get(path).status_code in (401, 404)


@pytest.mark.parametrize(
    "header",
    [
        "Bearer " + "x" * MIN_TOKEN_LENGTH,
        "Bearer " + TOKEN[:-1],
        "Bearer " + TOKEN + "x",
        "Bearer ",
        "Basic " + TOKEN,
        TOKEN,
    ],
)
def test_wrong_or_malformed_token_is_rejected_on_every_route(header):
    client = _client()
    for path in _every_route(client):
        if path in PUBLIC_PATHS:
            continue
        assert client.get(path, headers={"Authorization": header}).status_code == 401, path


def test_correct_token_is_accepted_on_every_route():
    client = _client()
    for path in _every_route(client):
        response = client.get(path, headers={"Authorization": f"Bearer {TOKEN}"})
        assert response.status_code == 200, path


def test_non_ascii_token_is_rejected_not_a_server_error():
    client = _client()
    response = client.get("/api/records", headers={"Authorization": "Bearer café".encode("latin-1")})
    assert response.status_code == 401


def test_create_app_refuses_a_weak_token():
    for weak in ("", " " * 40, "short", TOKEN[:-1], "a" * 32, "password" * 5):
        with pytest.raises(ApiTokenError):
            create_app(_session_factory(), api_token=weak)


def test_create_app_without_token_reads_the_environment(monkeypatch):
    monkeypatch.delenv(API_TOKEN_ENV, raising=False)
    monkeypatch.delenv("CREDENTIALS_DIRECTORY", raising=False)
    with pytest.raises(ApiTokenError):
        create_app(_session_factory())
    monkeypatch.setenv(API_TOKEN_ENV, TOKEN)
    client = TestClient(create_app(_session_factory()))
    assert client.get("/api/records", headers={"Authorization": f"Bearer {TOKEN}"}).status_code == 200


def test_load_api_token_missing_empty_and_weak_refuse():
    with pytest.raises(ApiTokenError, match=API_TOKEN_ENV):
        load_api_token({})
    with pytest.raises(ApiTokenError):
        load_api_token({API_TOKEN_ENV: ""})
    with pytest.raises(ApiTokenError, match=str(MIN_TOKEN_LENGTH)):
        load_api_token({API_TOKEN_ENV: "weak"})


def test_load_api_token_strips_whitespace_and_never_echoes_the_token():
    assert load_api_token({API_TOKEN_ENV: f" {TOKEN}\n"}) == TOKEN
    with pytest.raises(ApiTokenError) as excinfo:
        load_api_token({API_TOKEN_ENV: "weakweak"})
    assert "weakweak" not in str(excinfo.value)


def test_load_api_token_falls_back_to_systemd_credential(tmp_path):
    (tmp_path / "api_token").write_text(TOKEN + "\n")
    assert load_api_token({"CREDENTIALS_DIRECTORY": str(tmp_path)}) == TOKEN


def test_records_limit_default_is_well_under_the_old_5000_cap():
    client = _client(rows=150)
    body = client.get("/api/records", headers={"Authorization": f"Bearer {TOKEN}"}).json()
    assert len(body) == 100


def test_records_limit_is_capped_and_validated():
    client = _client(rows=5)
    headers = {"Authorization": f"Bearer {TOKEN}"}
    assert client.get("/api/records", params={"limit": 1000}, headers=headers).status_code == 200
    for bad in (1001, 5000, 0, -1, "abc", "1.5"):
        assert client.get("/api/records", params={"limit": bad}, headers=headers).status_code == 422


def test_records_offset_paginates():
    client = _client(rows=5)
    headers = {"Authorization": f"Bearer {TOKEN}"}
    first = client.get("/api/records", params={"limit": 2}, headers=headers).json()
    second = client.get("/api/records", params={"limit": 2, "offset": 2}, headers=headers).json()
    assert len(first) == 2 and len(second) == 2
    assert not {r["identifier"]["bssid"] for r in first} & {r["identifier"]["bssid"] for r in second}
    assert client.get("/api/records", params={"offset": -1}, headers=headers).status_code == 422


def test_server_binds_loopback_by_default(monkeypatch):
    import viz.app as app_module

    captured = {}
    monkeypatch.setenv(API_TOKEN_ENV, TOKEN)
    monkeypatch.setenv("SURVEYTOOL_DATABASE_URL", "sqlite:///:memory:")
    monkeypatch.setattr(app_module.uvicorn, "run", lambda app, **kw: captured.update(kw))
    app_module.main([])
    assert captured["host"] == "127.0.0.1"


def test_server_refuses_to_start_without_a_token(monkeypatch):
    import viz.app as app_module

    monkeypatch.delenv(API_TOKEN_ENV, raising=False)
    monkeypatch.delenv("CREDENTIALS_DIRECTORY", raising=False)
    monkeypatch.setattr(app_module.uvicorn, "run", lambda *a, **k: pytest.fail("server started"))
    with pytest.raises(SystemExit) as excinfo:
        app_module.main([])
    assert excinfo.value.code != 0


def test_offset_bounds_never_reach_the_database_as_an_overflow():
    client = _client(rows=1)
    headers = {"Authorization": f"Bearer {TOKEN}"}
    assert client.get("/api/records", params={"offset": 2**31 - 1}, headers=headers).status_code == 200
    for bad in (2**31, 2**63, 9223372036854775808, -1, "abc", "1.5"):
        assert client.get("/api/records", params={"offset": bad}, headers=headers).status_code == 422


def test_static_shell_is_public_and_carries_no_survey_data():
    client = TestClient(create_app(_session_factory(rows=3), api_token=TOKEN))
    response = client.get("/")
    assert response.status_code == 200
    assert "AA:BB:CC" not in response.text
    assert client.get("/api/records").status_code == 401


def test_static_shell_is_the_same_string_for_every_request_and_user_input_is_ignored():
    client = _client()
    assert client.get("/").text == client.get("/?x=<script>alert(1)</script>").text


def test_map_page_sends_the_token_in_a_header_and_never_stores_it_durably():
    client = TestClient(create_app(_session_factory(), api_token=TOKEN))
    html = client.get("/").text
    js = client.get("/static/map.js").text
    assert 'type="password"' in html
    assert "Authorization" in js and "Bearer" in js
    assert "localStorage" not in html + js
    assert "console." not in html + js
    assert "location.search" not in js and "location.hash" not in js
    assert "401" in js
    assert ".catch(" in js


def test_token_with_too_few_distinct_characters_is_refused():
    assert MIN_DISTINCT_CHARS == 16
    for weak in ("a" * 32, "password" * 5, "ab" * 40):
        with pytest.raises(ApiTokenError):
            load_api_token({API_TOKEN_ENV: weak})


@pytest.mark.parametrize("error", [PermissionError, IsADirectoryError, OSError])
def test_unreadable_credential_is_a_clean_startup_error(tmp_path, monkeypatch, error):
    def boom(self, *a, **k):
        raise error("secret-path-detail")

    monkeypatch.setattr("pathlib.Path.read_text", boom)
    with pytest.raises(ApiTokenError, match="api_token"):
        load_api_token({"CREDENTIALS_DIRECTORY": str(tmp_path)})


def test_credential_that_is_a_directory_is_a_clean_startup_error(tmp_path):
    (tmp_path / "api_token").mkdir()
    with pytest.raises(ApiTokenError):
        load_api_token({"CREDENTIALS_DIRECTORY": str(tmp_path)})


def test_server_exits_cleanly_when_the_credential_is_unreadable(monkeypatch, tmp_path):
    import viz.app as app_module

    (tmp_path / "api_token").mkdir()
    monkeypatch.delenv(API_TOKEN_ENV, raising=False)
    monkeypatch.setenv("CREDENTIALS_DIRECTORY", str(tmp_path))
    with pytest.raises(SystemExit) as excinfo:
        app_module.main([])
    assert excinfo.value.code != 0
